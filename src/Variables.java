/**
 * Variables
 * --------
 * Espacio en memoria cuyo valor puede modificarse durante la ejecución.
 */
public class Variables {
    public static void main(String[] args) {
        int edad = 28;                     // variable entera
        double salario = 3500.75;           // variable de punto flotante
        String nombre = "Laura";            // variable de referencia (String)

        System.out.println(nombre + " tiene " + edad + " años y gana $" + salario);
    }
}
